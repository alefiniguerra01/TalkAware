"""# Fine-tuning"""

import unsloth
from unsloth import FastLanguageModel, PatchDPOTrainer
import torch
from trl import DPOTrainer
max_seq_length = 2048 # Choose any! We auto support RoPE Scaling internally!
dtype = None # None for auto detection. Float16 for Tesla T4, V100, Bfloat16 for Ampere+
load_in_4bit = True # Use 4bit quantization to reduce memory usage. Can be False.

# caricamento del modello 3B
model_3b, tokenizer_3b = FastLanguageModel.from_pretrained(
    model_name = "unsloth/Llama-3.2-3B-Instruct",
    max_seq_length = max_seq_length,
    dtype = dtype,
    load_in_4bit = load_in_4bit,
)

model_3b = FastLanguageModel.get_peft_model(
    model_3b,
    r = 64, # Choose any number > 0 ! Suggested 8, 16, 32, 64, 128
    target_modules = ["q_proj", "k_proj", "v_proj", "o_proj",
                      "gate_proj", "up_proj", "down_proj",],
    lora_alpha = 32,
    lora_dropout = 0, # Supports any, but = 0 is optimized
    bias = "none",    # Supports any, but = "none" is optimized
    # [NEW] "unsloth" uses 30% less VRAM, fits 2x larger batch sizes!
    use_gradient_checkpointing = "unsloth", # True or "unsloth" for very long context
    random_state = 3407,
    use_rslora = False,  # We support rank stabilized LoRA
    loftq_config = None, # And LoftQ
)

from unsloth.chat_templates import get_chat_template
tokenizer = get_chat_template(
    tokenizer_3b,
    chat_template = "llama-3.1",
)

def add_chat(example):
    system = 'Data una frase nel contesto di una conversazione tra partner in una relazione sentimentale, determina se la frase è un esempio di linguaggio tossico o no. In caso affermativo, specifica se la frase rappresenta un caso di cyberviolenza o di violenza di altro tipo e spiegane le motivazioni. Rispondi ESCLUSIVAMENTE in italiano corretto e fluente. Non usare parole in altre lingue.'
    user = example['testo tradotto dallo spagnolo']
    output = ''
    if example['label toxic'] == 0:
        output = 'Questa frase non è tossica.'
    else:
        output = example['Spiegazione']
    messages = [{"role": "system", "content": system}, {"role": "user", "content": user},{"role": "assistant", "content": output}]
    return{"messages": messages}

def format_dataset(examples):
    messages = examples["messages"]
    text = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=False)
    return {"text": text}

dataset_tr = ft_dataset['train'].map(add_chat, remove_columns=ft_dataset['train'].column_names)
print(dataset_tr)

dataset_tr = dataset_tr.map(format_dataset, batched=True)
print(dataset_tr)

from trl import SFTTrainer
from transformers import TrainingArguments, DataCollatorForSeq2Seq
from unsloth import is_bfloat16_supported
import psutil
import builtins
