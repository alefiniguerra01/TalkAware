"""# DPO Training"""

PatchDPOTrainer()

def add_chat_dpo(example):
    system = 'Data una frase nel contesto di una conversazione tra partner in una relazione sentimentale, determina se la frase è un esempio di linguaggio tossico o no. In caso affermativo, specifica se la frase rappresenta un caso di cyberviolenza o di violenza di altro tipo e spiegane le motivazioni. Rispondi ESCLUSIVAMENTE in italiano corretto e fluente. Non usare parole in altre lingue.'
    user_input = (
        f"Contesto: {example['Contesto']}\n"
        f"Frase: {example['Esempio']}"
    )
    accept_msg = [{"role": "system", "content": system}, {"role": "user", "content": user_input},{"role": "assistant", "content": example['Accept']}]
    reject_msg = [{"role": "system", "content": system}, {"role": "user", "content": user_input},{"role": "assistant", "content": example['Reject']}]
    return {"chosen": accept_msg, "rejected": reject_msg}

def format_dataset_dpo(examples):
    text_chosen = tokenizer_3b.apply_chat_template(examples['chosen'], tokenize=False, add_generation_prompt=False)
    text_rejected = tokenizer_3b.apply_chat_template(examples['rejected'], tokenize=False, add_generation_prompt=False)
    return {"chosen": text_chosen, "rejected": text_rejected}

dpo_org_dataset = load_dataset("csv", data_files="toxic_dpo.csv")
print(dpo_org_dataset)
dpo_org_dataset = dpo_org_dataset['train'].map(add_chat_dpo, remove_columns=dpo_org_dataset['train'].column_names)
print(dpo_org_dataset)
dpo_org_dataset = dpo_org_dataset.map(format_dataset_dpo, batched=True)
print(dpo_org_dataset)

