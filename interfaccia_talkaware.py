# verifica che la scelta dell'utente sia Sì o No
def control_choice(history, user_choice):
  if user_choice not in ["👍 Sì", "👎 No"]:
    for msg in reversed(history):
      if msg["role"] == "user" and "choice" in msg["meta"]:
        user_choice = msg["content"]
      break
  return user_choice

