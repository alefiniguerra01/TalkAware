# Processes the user's sentence and returns the assistant's response.

def process_sentence(context, sentence):
  user_input = (
      f"Contesto: {context}\n"
      f"Frase: {sentence}"
  )

  # Construct the conversation messages
  messages = [
      {"role": "system", "content": system},
      {"role": "user", "content": user_input}
  ]
  # Tokenize and prepare the input tensors using the chat template
  inputs = tokenizer.apply_chat_template(
      messages,
      tokenize = True,
      add_generation_prompt = True,
      return_tensors = "pt",
  ).to(device)

  result = infer_with_3b(inputs)
  return result.strip()

